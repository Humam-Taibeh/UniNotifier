"""
The timetable the bot builds by itself — for a student who has no schedule.json.

Two things the bot already reads are enough:

  * the portal's home page (classtable.py -> data/class_table.json): every section you take
    with its course code, Arabic name, section, room, and each day's time and mode;
  * Moodle's course list (saved_items.json "courses"): each course's code — Moodle's idnumber
    is the portal's course code, with "_<section>" after it for a sectioned course (measured
    on the live site) — and its name as Moodle writes it, "20261-Big Data-AllSec-3": the name
    students know, the semester and the credit hours.

Joined by the course code — never by comparing names — they give a schedule of the same shape as
schedule.json, kept in data/schedule.auto.json (schedule.AUTO_FILE). schedule.load_schedule()
uses it only when there is no schedule.json: a timetable written by hand always wins.

A course Moodle does not list (not opened there yet) keeps the portal's Arabic name: nothing is
made up. The file is rewritten only when its content changes.
"""

import json
import logging
import re
from collections import Counter

from uninotifier import fileio, paths, schedule, timetable
from uninotifier.archive import course_folder_name

log = logging.getLogger("uninotifier")

STATE_FILE = paths.DATA / "saved_items.json"        # the monitor's state: the Moodle courses
TABLE_FILE = paths.DATA / "class_table.json"        # classtable's cache: the portal's timetable
WEEK = ("sun", "mon", "tue", "wed", "thu", "fri", "sat")
TERMS = {"1": "First Semester", "2": "Second Semester", "3": "Summer Semester"}
LABELS = {"In-Person": "In-Person Lecture", "Blended": "Blended Lecture", "Online": "Online Lecture",
          "Activity": "Activity / Self-Study"}
LAB = "عملي"                                         # the portal's word for a practical section
ROOM_MODES = ("In-Person", "Blended")               # a room only means something on a campus day
COMMENT = ["Built by the bot from the portal's timetable and Moodle's course list.",
           "Do not edit this file: it is rewritten. Write your own schedule.json instead - it always wins."]

_TERM = re.compile(r"^(\d{4})(\d)-")
_HOURS = re.compile(r"-(?:AllSec|Sec\d+|ش\d+)-(\d+(?:\.\d+)?)(?:-|$)")


def course_code(idnumber: str | None) -> str:
    """'0420115_12' -> '0420115': the portal's course code inside Moodle's idnumber."""
    return (idnumber or "").split("_", 1)[0].strip()


def hours_of(full_name: str) -> float | None:
    """'20261-Big Data-AllSec-3' -> 3.0; None when the name does not carry them."""
    found = _HOURS.search(full_name or "")
    return float(found.group(1)) if found else None


def semester_name(full_names) -> str | None:
    """'20261-…' -> 'First Semester 2026/2027': the term most of the courses belong to."""
    terms = Counter(found.groups() for found in map(_TERM.match, full_names or ()) if found)
    if not terms:
        return None
    year, term = terms.most_common(1)[0][0]
    return f"{TERMS[term]} {year}/{int(year) + 1}" if term in TERMS else None


def course_index(courses: dict) -> dict[str, dict]:
    """Moodle's courses by the portal's code: {code: {"name", "hours", "full"}}."""
    index = {}
    for course in (courses or {}).values():
        code = course_code(course.get("code"))
        if code and course.get("name"):
            index.setdefault(code, {"name": display_name(course["name"]), "hours": hours_of(course["name"]),
                                    "full": course["name"]})
    return index


def display_name(full_name: str) -> str:
    """'20261-Numerical Analysis(1)-AllSec-3-B' -> 'Numerical Analysis (1)': the course's name as
    Moodle writes it, with the space a bracket should have before it."""
    return re.sub(r"(?<=[^\s(])\(", " (", course_folder_name(full_name))


def build(slots: list[dict], courses: dict) -> dict | None:
    """The schedule for these class-table slots (classtable.slots_from_rows) and Moodle courses;
    None when there is no class to put in it."""
    index = course_index(courses)
    days: dict[str, list[dict]] = {}
    codes: dict[str, str] = {}
    seen = set()
    for slot in slots or []:
        try:
            key = (slot["day"], slot["start"], slot["end"], slot.get("code"), slot.get("section"))
            day, mode = slot["day"], slot["mode"]
        except (KeyError, TypeError):
            continue
        if key in seen or day not in WEEK or mode not in LABELS:
            continue
        seen.add(key)
        code = (slot.get("code") or "").strip()
        arabic = (slot.get("course_ar") or "").strip()
        name = (index.get(code) or {}).get("name") or arabic or code
        if not name:
            continue
        section = (slot.get("section") or "").strip()
        lecture = {"start": slot["start"], "end": slot["end"], "course": name, "course_ar": arabic or name,
                   "section": section.zfill(2) if section.isdigit() else section or "-", "mode": mode,
                   "label": "Lab" if LAB in (slot.get("activity") or "") else LABELS[mode]}
        room = (slot.get("room") or "").strip()
        if room and mode in ROOM_MODES:
            lecture["place"] = timetable.room(f"Room {room}")      # the one short form: "Room 9147", "Room م9135"
        days.setdefault(day, []).append(lecture)
        if code:
            codes.setdefault(code, name)
    if not days:
        return None
    for lectures in days.values():
        lectures.sort(key=lambda lec: (lec["start"], lec["end"], lec["course"]))
    built = {"_comment": COMMENT, "lecture_reminder_minutes": 60, "remind_modes": ["Online"],
             "course_codes": dict(sorted(codes.items())),
             "days": {day: days[day] for day in WEEK if day in days}}
    semester = semester_name([c["full"] for c in index.values()])
    if semester:
        built = {"_comment": COMMENT, "semester": semester, **{k: v for k, v in built.items() if k != "_comment"}}
    return built


def _read(path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def refresh() -> bool:
    """Build the schedule from what is on file now and keep it. True when the file changed.
    With no class table there is nothing to build, and a file already kept is left alone."""
    built = build(_read(TABLE_FILE).get("slots") or [], _read(STATE_FILE).get("courses") or {})
    if built is None:
        return False
    problems = schedule.validate(built)
    if problems:                                # never keep a schedule the reminders could not use
        log.error("The timetable built from the portal is not usable (%s)", "; ".join(problems[:3]))
        return False
    if _read(schedule.AUTO_FILE) == built:
        return False
    fileio.write_json_atomic(schedule.AUTO_FILE, built)
    log.info("Timetable built from the portal: %d class(es) over %d day(s)",
             sum(len(v) for v in built["days"].values()), len(built["days"]))
    return True


def hours_for(current: dict) -> dict[str, float]:
    """{course name: credit hours} for the schedule in force, from Moodle's course names by the
    codes the schedule lists ("course_codes"); a course without a known code is left out."""
    index = course_index(_read(STATE_FILE).get("courses") or {})
    hours = {}
    for code, name in (current.get("course_codes") or {}).items():
        found = (index.get(code) or {}).get("hours")
        if found is not None:
            hours[name] = found
    return hours


if __name__ == "__main__":         # python -m uninotifier.autoschedule — build it now
    print("built" if refresh() else "nothing new to build")
